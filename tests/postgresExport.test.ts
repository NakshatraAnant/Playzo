/** PostgreSQL export: no SQLite-only syntax survives, tables load in foreign-key order, data is quoted safely. */
import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { Db } from '../server/db';

describe('export:postgres', () => {
  it('translates the full PLAYZO schema and data', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pz-pg-'));
    const file = path.join(dir, 'src.db');
    const d = new Db(file);
    d.migrate();
    d.run("INSERT INTO users (id, username, display_name, dob, age_band) VALUES ('u1', 'O''Brien', 'Quote''s; DROP TABLE users;--', '1990-01-01', 'adult')");
    d.run("INSERT INTO audit_log (actor, action) VALUES ('u1', 'test')");
    d.raw.close();
    const out = path.join(dir, 'out');
    execFileSync(process.execPath, ['--import', 'tsx', 'scripts/export-postgres.ts', file, out], { stdio: 'pipe' });
    const schema = fs.readFileSync(path.join(out, 'schema.sql'), 'utf8');
    const data = fs.readFileSync(path.join(out, 'data.sql'), 'utf8');
    expect(schema).not.toMatch(/strftime|AUTOINCREMENT|COLLATE NOCASE|INSERT OR/);
    expect(schema).toContain('GENERATED BY DEFAULT AS IDENTITY');
    expect(schema).toContain('playzo_append_only');
    // users must be created before tables that reference it.
    expect(schema.indexOf('CREATE TABLE IF NOT EXISTS users')).toBeLessThan(schema.indexOf('CREATE TABLE IF NOT EXISTS ledger'));
    expect(data).toContain("'Quote''s; DROP TABLE users;--'");
    expect(data).toMatch(/setval\(pg_get_serial_sequence\('audit_log', 'id'\)/);
    fs.rmSync(dir, { recursive: true, force: true });
  });
});
