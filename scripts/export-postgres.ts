/**
 * PostgreSQL migration path: exports the live SQLite database as PostgreSQL DDL + data.
 *
 *   npm run export:postgres            -> data/postgres-export/{schema.sql,data.sql,README.txt}
 *   psql "$DATABASE_URL" -f data/postgres-export/schema.sql
 *   psql "$DATABASE_URL" -f data/postgres-export/data.sql
 *
 * The export reads the database read-only and never modifies it. data.sql contains personal data:
 * it is written under data/ (gitignored); handle it like a backup. PostgreSQL was not available on the
 * build machine, so the output was generated and statically checked here, not loaded into Postgres.
 */
import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { config } from '../server/config';

const src = process.argv[2] ?? config.dbPath;
const outDir = path.resolve(process.argv[3] ?? 'data/postgres-export');
const d = new DatabaseSync(src, { readOnly: true });
const tables = (d.prepare("SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all() as { name: string; sql: string }[]);
const NOW = `to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`;

/** Translate one SQLite CREATE TABLE statement to PostgreSQL. */
export function toPg(sql: string): string {
  return sql
    .replace(/--[^\n]*/g, '')
    .replace(/\(strftime\('%Y-%m-%dT%H:%M:%fZ','now'\)\)/g, `(${NOW})`)
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bCOLLATE NOCASE\b/g, '') // case-insensitive username uniqueness: see the unique index below
    .replace(/\bINTEGER\b/g, 'BIGINT')
    .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
    .replace(/CREATE TABLE (\w+)/, 'CREATE TABLE IF NOT EXISTS $1')
    .replace(/[ \t]+\n/g, '\n');
}

// Dependency order (referenced tables first) so foreign keys load cleanly.
const refs = new Map(tables.map((t) => [t.name, [...t.sql.matchAll(/REFERENCES (\w+)/g)].map((m) => m[1]).filter((r) => r !== t.name)]));
const ordered: string[] = [];
const visit = (n: string, seen = new Set<string>()) => { if (ordered.includes(n) || seen.has(n)) return; seen.add(n); for (const r of refs.get(n) ?? []) visit(r, seen); ordered.push(n); };
for (const t of tables) visit(t.name);

const schema: string[] = ['-- PLAYZO PostgreSQL schema (generated from SQLite by scripts/export-postgres.ts)', 'BEGIN;'];
for (const n of ordered) schema.push(toPg(tables.find((t) => t.name === n)!.sql) + ';');
for (const ix of d.prepare("SELECT sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL").all() as { sql: string }[]) schema.push(ix.sql.replace(/CREATE (UNIQUE )?INDEX (IF NOT EXISTS )?/, 'CREATE $1INDEX IF NOT EXISTS ') + ';');
schema.push(`CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON users (lower(username));`);
schema.push(`-- Append-only ledger and audit log (SQLite triggers translated).
CREATE OR REPLACE FUNCTION playzo_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' AND TG_TABLE_NAME = 'ledger' AND NOT EXISTS (SELECT 1 FROM users WHERE id = OLD.user_id) THEN RETURN OLD; END IF;
  RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END $$;
DROP TRIGGER IF EXISTS ledger_append_only ON ledger;
CREATE TRIGGER ledger_append_only BEFORE UPDATE OR DELETE ON ledger FOR EACH ROW EXECUTE FUNCTION playzo_append_only();
DROP TRIGGER IF EXISTS audit_append_only ON audit_log;
CREATE TRIGGER audit_append_only BEFORE UPDATE OR DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION playzo_append_only();`);
schema.push('COMMIT;');

const lit = (v: unknown) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' || typeof v === 'bigint' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const data: string[] = ['-- PLAYZO data export (contains personal data: store securely, never commit)', 'BEGIN;', "SET session_replication_role = 'replica';"];
const counts: Record<string, number> = {};
for (const n of ordered) {
  const rows = d.prepare(`SELECT * FROM "${n}"`).all() as Record<string, unknown>[];
  counts[n] = rows.length;
  for (let i = 0; i < rows.length; i += 200) {
    const chunk = rows.slice(i, i + 200);
    const cols = Object.keys(chunk[0]);
    data.push(`INSERT INTO ${n} (${cols.map((c) => `"${c}"`).join(', ')}) VALUES\n${chunk.map((r) => `(${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n')};`);
  }
  const identity = /(\w+) INTEGER PRIMARY KEY AUTOINCREMENT/.exec(tables.find((t) => t.name === n)!.sql)?.[1];
  if (identity && rows.length) data.push(`SELECT setval(pg_get_serial_sequence('${n}', '${identity}'), (SELECT MAX("${identity}") FROM ${n}));`);
}
data.push("SET session_replication_role = 'origin';", 'COMMIT;');
d.close();

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'schema.sql'), schema.join('\n\n') + '\n');
fs.writeFileSync(path.join(outDir, 'data.sql'), data.join('\n') + '\n');
fs.writeFileSync(path.join(outDir, 'README.txt'), `PLAYZO PostgreSQL export\nSource: ${src}\nTables: ${ordered.length}\nRows: ${JSON.stringify(counts)}\n\nLoad:\n  psql "$DATABASE_URL" -f schema.sql\n  psql "$DATABASE_URL" -f data.sql\n\nNotes: timestamps stay ISO-8601 TEXT (as in SQLite); JSON columns stay TEXT (convert to jsonb later if wanted).\nThe application still runs on SQLite; switching its data layer to PostgreSQL is a separate change (server/db.ts).\n`);
console.log(`[export] ${ordered.length} tables, ${Object.values(counts).reduce((a, b) => a + b, 0)} rows -> ${outDir}`);
